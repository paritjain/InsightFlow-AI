import re
import difflib
from typing import Dict, List, Optional, Tuple, Any

class SemanticLayer:
    """
    Reusable Dataset-Agnostic Semantic Layer.
    Maps natural-language concepts and query terms to actual columns in any uploaded dataset
    using Data Dictionary metadata, exact/normalized matching, fuzzy matching, synonyms, and statistical evidence.
    """

    def __init__(self, sem_layer_dict: Dict[str, Any]):
        """
        sem_layer_dict: Dictionary mapping column_name -> metadata dict generated by infer_column_semantic_metadata
        """
        self.sem_layer = sem_layer_dict
        self._build_indexes()

    def _build_indexes(self):
        self.column_map = {}       # clean_lower -> actual col name
        self.norm_map = {}         # alphanumeric_norm -> actual col name
        self.measures = []         # list of actual col names
        self.dimensions = []       # list of actual col names
        self.time_cols = []        # list of actual col names
        self.id_cols = []          # list of actual col names

        self.primary_keys = []
        self.foreign_keys = []

        for col, meta in self.sem_layer.items():
            c_str = str(col)
            c_low = c_str.lower().strip()
            norm = re.sub(r'[^a-z0-9]+', '', c_low)

            self.column_map[c_low] = c_str
            self.norm_map[norm] = c_str

            role = meta.get("semantic_role", "Dimension")
            canonical_role = meta.get("canonical_role", "")
            
            is_pk = meta.get("is_primary_key", False) or role == "Primary Key" or canonical_role == "PRIMARY KEY"
            is_fk = meta.get("is_foreign_key", False) or role == "Foreign Key" or canonical_role == "FOREIGN KEY"
            is_id = meta.get("is_identifier", False) or role in ["Identifier", "ID", "IDENTIFIER", "Primary Key", "Foreign Key"] or canonical_role in ["IDENTIFIER", "PRIMARY KEY", "FOREIGN KEY"] or is_pk or is_fk
            is_meas = meta.get("is_measure", False) or role in ["Measure", "Target/Outcome", "NUMERIC MEASURE"] or canonical_role == "NUMERIC MEASURE"
            is_time = meta.get("is_time", False) or role in ["Date/Time", "Time", "TEMPORAL"] or canonical_role == "TEMPORAL"
            is_dim = meta.get("is_dimension", False) or role in ["Dimension", "Geographic", "Boolean", "CATEGORICAL DIMENSION", "Category", "Binary Category"] or canonical_role == "CATEGORICAL DIMENSION"

            if is_pk:
                self.primary_keys.append(c_str)
            if is_fk:
                self.foreign_keys.append(c_str)
            if is_id:
                self.id_cols.append(c_str)
            if is_meas and not is_id:
                self.measures.append(c_str)
            if is_time and not is_id:
                self.time_cols.append(c_str)
            if is_dim and not is_id and not is_meas:
                self.dimensions.append(c_str)

        # Fallback safeguard: ensure columns not caught are indexed
        for col in self.sem_layer.keys():
            c_str = str(col)
            if c_str not in self.measures and c_str not in self.dimensions and c_str not in self.time_cols and c_str not in self.id_cols:
                meta = self.sem_layer[col]
                dtype_str = str(meta.get("physical_dtype", "")).lower()
                if "int" in dtype_str or "float" in dtype_str or "double" in dtype_str:
                    self.measures.append(c_str)
                elif "date" in dtype_str or "time" in dtype_str:
                    self.time_cols.append(c_str)
                else:
                    self.dimensions.append(c_str)

    def resolve_column(self, term: str, role_filter: Optional[str] = None) -> Optional[Tuple[str, float]]:
        """
        Resolves a search term/concept to the best matching column in the dataset.
        Priority:
        1. Exact column name match
        2. Normalized column name match
        3. Substring match in column name
        4. Cross-industry business alias / concept match
        5. Fuzzy string similarity matching (SequenceMatcher)
        6. Data Dictionary business meaning / description match

        Returns: (column_name, confidence_score) or None
        """
        if not term:
            return None

        t_low = term.lower().strip()
        t_norm = re.sub(r'[^a-z0-9]+', '', t_low)

        # 1. Exact match
        if t_low in self.column_map:
            col = self.column_map[t_low]
            if self._matches_role(col, role_filter):
                return col, 1.0

        # 2. Normalized match
        if t_norm in self.norm_map:
            col = self.norm_map[t_norm]
            if self._matches_role(col, role_filter):
                return col, 0.95

        # 3. Substring match (e.g., query asks for "amount", column is "total_amount")
        for c_low, col in self.column_map.items():
            if (t_low in c_low or c_low in t_low) and len(t_low) >= 3:
                if self._matches_role(col, role_filter):
                    return col, 0.88

        # 4. Cross-industry Domain Alias Matching
        alias_match = self._match_by_synonyms(t_low, role_filter)
        if alias_match:
            return alias_match

        # 5. Fuzzy string similarity matching (difflib SequenceMatcher)
        best_fuzzy_col = None
        best_fuzzy_ratio = 0.0
        candidate_cols = []
        if role_filter == "Measure":
            candidate_cols = self.measures
        elif role_filter == "Dimension":
            candidate_cols = self.dimensions + self.id_cols
        elif role_filter == "Time":
            candidate_cols = self.time_cols
        else:
            candidate_cols = list(self.column_map.values())

        for col in candidate_cols:
            c_low = col.lower()
            ratio = difflib.SequenceMatcher(None, t_low, c_low).ratio()
            # Also check partial ratio on words
            words = c_low.replace('_', ' ').split()
            for w in words:
                w_ratio = difflib.SequenceMatcher(None, t_low, w).ratio()
                if w_ratio > ratio:
                    ratio = w_ratio
            if ratio > best_fuzzy_ratio:
                best_fuzzy_ratio = ratio
                best_fuzzy_col = col

        if best_fuzzy_ratio >= 0.75 and best_fuzzy_col:
            if self._matches_role(best_fuzzy_col, role_filter):
                return best_fuzzy_col, round(best_fuzzy_ratio * 0.9, 2)

        # 6. Data Dictionary Description Match
        stopwords = {
            'for', 'the', 'and', 'with', 'from', 'this', 'that', 'dataset', 'column',
            'records', 'identifier', 'unique', 'measure', 'dimension', 'each', 'all',
            'what', 'which', 'who', 'how', 'many', 'calculate', 'mean', 'total', 'average',
            'sum', 'count', 'data', 'primary', 'foreign', 'metric', 'role'
        }
        if t_low not in stopwords and len(t_low) >= 4:
            for col, meta in self.sem_layer.items():
                desc = str(meta.get("description", "")).lower()
                if t_low in desc:
                    if self._matches_role(col, role_filter):
                        return col, 0.70

        return None

    def _matches_role(self, col: str, role_filter: Optional[str]) -> bool:
        if not role_filter:
            return True
        meta = self.sem_layer.get(col, {})
        col_role = meta.get("semantic_role")
        canonical_role = meta.get("canonical_role", "")

        is_meas = meta.get("is_measure", False) or col in self.measures or col_role in ["Measure", "Target/Outcome", "NUMERIC MEASURE"] or canonical_role == "NUMERIC MEASURE"
        is_dim = meta.get("is_dimension", False) or col in self.dimensions or col_role in ["Dimension", "Geographic", "Boolean", "CATEGORICAL DIMENSION", "Category"] or canonical_role == "CATEGORICAL DIMENSION"
        is_time = meta.get("is_time", False) or col in self.time_cols or col_role in ["Date/Time", "Time", "TEMPORAL"] or canonical_role == "TEMPORAL"
        is_id = meta.get("is_identifier", False) or col in self.id_cols or col_role in ["Identifier", "ID", "IDENTIFIER"] or canonical_role == "IDENTIFIER"

        if role_filter == "Measure":
            return is_meas and not is_id
        elif role_filter == "Dimension":
            # Dynamic Role Fallback: Allow discrete string/integer/ID columns dynamically as valid dimensions for grouping/ranking
            return is_dim or is_time or is_id or meta.get("grouping_eligibility", True)
        elif role_filter == "Time":
            return is_time and not is_id
        elif role_filter == "ID":
            return is_id
        return True

    def _match_by_synonyms(self, term: str, role_filter: Optional[str]) -> Optional[Tuple[str, float]]:
        """Matches domain-agnostic concepts across Logistics, Finance, E-commerce, HR, etc."""
        measure_synonyms = {
            "Currency": [
                'revenue', 'sales', 'turnover', 'profit', 'cost', 'expense', 'price', 'spend', 
                'amount', 'income', 'salary', 'wage', 'fee', 'charge', 'mrr', 'arr', 'value',
                'gmv', 'freight', 'shipping_cost', 'discount_amount', 'budget', 'operating_cost'
            ],
            "Percentage": [
                'discount', 'margin', 'percentage', 'pct', 'rate', 'ratio', 'share', 
                'conversion', 'yield', 'growth', 'attrition_rate', 'retention_rate'
            ],
            "Rating": [
                'rating', 'score', 'satisfaction', 'nps', 'feedback', 'grade', 'evaluation', 'performance'
            ],
            "Duration": [
                'duration', 'tenure', 'days', 'hours', 'minutes', 'delay', 'lead_time', 
                'time_taken', 'delivery_time', 'transit_time', 'cycle_time'
            ],
            "Quantity": [
                'qty', 'quantity', 'units', 'items', 'volume', 'count', 'batch_size', 
                'headcount', 'orders', 'distance', 'mileage', 'weight', 'capacity'
            ]
        }

        # Check if term matches any measure subtype
        for subtype, keywords in measure_synonyms.items():
            if any(kw in term for kw in keywords) or term in keywords:
                for col in self.measures:
                    meta = self.sem_layer.get(col, {})
                    c_low = col.lower()
                    if meta.get("semantic_subtype") == subtype or any(kw in c_low for kw in keywords):
                        if self._matches_role(col, role_filter):
                            return col, 0.82

        # Temporal synonyms
        if any(kw in term for kw in ['date', 'time', 'period', 'month', 'year', 'week', 'quarter', 'timestamp', 'day', 'orderdate', 'bookingdate']):
            if self.time_cols:
                return self.time_cols[0], 0.85

        # Geographic / Location dimension synonyms
        if any(kw in term for kw in ['region', 'location', 'country', 'state', 'city', 'territory', 'plant', 'warehouse', 'branch', 'office', 'origin', 'destination', 'zone']):
            for col in self.dimensions:
                meta = self.sem_layer.get(col, {})
                if meta.get("semantic_subtype") == "Geographic" or any(kw in col.lower() for kw in ['region', 'location', 'country', 'state', 'city', 'plant', 'branch', 'warehouse', 'zone']):
                    if self._matches_role(col, role_filter):
                        return col, 0.80

        # Segment / Category / Entity dimension synonyms
        if any(kw in term for kw in ['category', 'segment', 'type', 'group', 'tier', 'department', 'channel', 'mode', 'status', 'customer', 'carrier', 'product', 'employee', 'vendor']):
            for col in self.dimensions:
                meta = self.sem_layer.get(col, {})
                if meta.get("grouping_eligibility", True):
                    c_low = col.lower()
                    if any(kw in c_low for kw in ['category', 'segment', 'type', 'group', 'tier', 'department', 'channel', 'status', 'mode', 'carrier', 'product', 'customer', 'dept', 'role']):
                        if self._matches_role(col, role_filter):
                            return col, 0.80

        return None

